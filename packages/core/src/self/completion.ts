/**
 * Shell-completion generation (completion capability r110): the command tree
 * is captured as a plain IR in the CLI layer (commander is a CLI dependency —
 * core stays pure), then rendered per shell here. No second command manifest:
 * the IR is extracted from the live commander program on every invocation, so
 * tree changes flow through automatically. Zero persistence, zero I/O.
 */

export interface CompletionCommandSpec {
  name: string;
  /** Long flags only (e.g. `--directory`), including the ones on this node. */
  flags: string[];
  subcommands: CompletionCommandSpec[];
}

export type CompletionShell = 'bash' | 'zsh' | 'fish' | 'powershell' | 'elvish';

export const COMPLETION_SHELLS: readonly CompletionShell[] = [
  'bash',
  'zsh',
  'fish',
  'powershell',
  'elvish',
];

/** The binary name baked into generated scripts and rc snippets (bin field). */
export const COMPLETION_BIN = 'llman-sdd';

export const COMPLETION_MARKER_START = '# >>> llman-sdd completion >>>';
export const COMPLETION_MARKER_END = '# <<< llman-sdd completion <<<';

export function isCompletionShell(value: string): value is CompletionShell {
  return (COMPLETION_SHELLS as readonly string[]).includes(value);
}

/** Union of long flags across the whole tree, sorted, deduped. */
export function collectFlags(spec: CompletionCommandSpec): string[] {
  const out = new Set<string>(spec.flags);
  for (const sub of spec.subcommands) for (const f of collectFlags(sub)) out.add(f);
  return [...out].toSorted();
}

/**
 * Render a complete completion script for one shell. Every renderer MUST
 * embed the bin name, every top-level command, and `--directory` — the BDD
 * suite pins these spot-checks against the live commander tree.
 */
export function renderCompletionScript(
  spec: CompletionCommandSpec,
  shell: CompletionShell,
): string {
  const top = spec.subcommands.map((c) => c.name);
  const flags = collectFlags(spec);
  switch (shell) {
    case 'bash':
      return renderBash(spec, top, flags);
    case 'zsh':
      return renderZsh(top, flags);
    case 'fish':
      return renderFish(spec, top, flags);
    case 'powershell':
      return renderPowerShell(top, flags);
    case 'elvish':
      return renderElvish(top, flags);
  }
}

const header = (shell: string): string =>
  `# ${COMPLETION_BIN} completion — ${shell} (generated by \`${COMPLETION_BIN} self completion --shell ${shell}\`; do not edit by hand)\n`;

function quoted(names: readonly string[]): string {
  return names.map((n) => `'${n}'`).join(' ');
}

function renderBash(spec: CompletionCommandSpec, top: string[], flags: string[]): string {
  const fn = `_${COMPLETION_BIN.replaceAll('-', '_')}_completion`;
  const perCommand = spec.subcommands
    .filter((c) => c.flags.length > 0)
    .map((c) => `    ${c.name}) local flags="${c.flags.join(' ')} $flags" ;;`)
    .join('\n');
  return `${header('bash')}
${fn}() {
  local cur="\${COMP_WORDS[COMP_CWORD]}"
  local commands="${top.join(' ')}"
  local flags="${flags.join(' ')}"
  if [[ "$cur" == -* ]]; then
    case "\${COMP_WORDS[1]}" in
${perCommand}
      *) ;;
    esac
    COMPREPLY=( $(compgen -W "$flags" -- "$cur") )
  else
    COMPREPLY=( $(compgen -W "$commands" -- "$cur") )
  fi
}
complete -F ${fn} ${COMPLETION_BIN}
`;
}

function renderZsh(top: string[], flags: string[]): string {
  return `${header('zsh')}
#compdef ${COMPLETION_BIN}
_${COMPLETION_BIN.replaceAll('-', '_')}() {
  local -a cmds
  cmds=(${quoted(top)})
  if [[ "$CURRENT" == 2 && "$words[2]" != -* ]]; then
    _describe 'command' cmds
  else
    local -a flgs
    flgs=(${quoted(flags)})
    _describe 'flag' flgs
  fi
}
compdef _${COMPLETION_BIN.replaceAll('-', '_')} ${COMPLETION_BIN}
`;
}

function renderFish(spec: CompletionCommandSpec, top: string[], flags: string[]): string {
  const lines: string[] = [
    `complete -c ${COMPLETION_BIN} -f`,
    `complete -c ${COMPLETION_BIN} -f -a '${top.join(' ')}' -n '__fish_is_first_arg'`,
  ];
  for (const f of flags) lines.push(`complete -c ${COMPLETION_BIN} -f -l ${f.replace(/^--/u, '')}`);
  for (const c of spec.subcommands) {
    for (const f of c.flags) {
      lines.push(
        `complete -c ${COMPLETION_BIN} -f -n '__fish_seen_subcommand_from ${c.name}' -l ${f.replace(/^--/u, '')}`,
      );
    }
    if (c.subcommands.length > 0) {
      lines.push(
        `complete -c ${COMPLETION_BIN} -f -n '__fish_seen_subcommand_from ${c.name}' -a '${c.subcommands.map((s) => s.name).join(' ')}'`,
      );
    }
  }
  return `${header('fish')}${lines.join('\n')}\n`;
}

function renderPowerShell(top: string[], flags: string[]): string {
  return `${header('powershell')}
Register-ArgumentCompleter -CommandName ${COMPLETION_BIN} -ScriptBlock {
  param($wordToComplete, $commandAst, $cursorPosition)
  $commands = @(${quoted(top)})
  $flags = @(${quoted(flags)})
  $pool = if ($wordToComplete.StartsWith('-')) { $flags } else { $commands }
  $pool | Where-Object { $_ -like "$wordToComplete*" } | ForEach-Object {
    [System.Management.Automation.CompletionResult]::new($_)
  }
}
`;
}

function renderElvish(top: string[], flags: string[]): string {
  return `${header('elvish')}
edit:completion:arg-completer[${COMPLETION_BIN}] = [@args] {
  cur = $args[-1]
  cmds = [${top.join(' ')}]
  flgs = [${flags.join(' ')}]
  if (str:has-prefix $cur -) {
    put $@flgs
  } else {
    put $@cmds
  }
}
`;
}

/** Full marker-wrapped block written into an rc/profile. */
export function completionBlock(snippet: string): string {
  return `${COMPLETION_MARKER_START}\n${snippet}\n${COMPLETION_MARKER_END}`;
}

/**
 * Marker-idempotent upsert (completion capability r111): an existing block is
 * replaced in place (block count never grows); otherwise the block is
 * appended. Pure string transform — the caller owns file I/O.
 */
export function upsertCompletionBlock(
  existing: string,
  snippet: string,
): { content: string; replaced: boolean } {
  const block = completionBlock(snippet);
  const startAt = existing.indexOf(COMPLETION_MARKER_START);
  const endAt = existing.indexOf(COMPLETION_MARKER_END);
  if (startAt >= 0 && endAt >= 0 && endAt >= startAt) {
    const content = `${existing.slice(0, startAt)}${block}${existing.slice(endAt + COMPLETION_MARKER_END.length)}`;
    return { content, replaced: true };
  }
  const glue = existing === '' || existing.endsWith('\n') ? '' : '\n';
  return { content: `${existing}${glue}${block}\n`, replaced: false };
}

/**
 * Bash rc fallback chain (r111): `.bashrc` → `.bash_profile` → `.profile`;
 * when none exists the chain lands back on `.bashrc` (the caller creates it).
 * `exists` is injected so core stays filesystem-free.
 */
export function resolveBashRc(home: string, exists: (p: string) => boolean): string {
  const bashrc = `${home}/.bashrc`;
  if (exists(bashrc)) return bashrc;
  const bashProfile = `${home}/.bash_profile`;
  if (exists(bashProfile)) return bashProfile;
  const profile = `${home}/.profile`;
  if (exists(profile)) return profile;
  return bashrc;
}
